// Viridian Forge — level-calibration table generator.
//
// Every amp model/channel is level-matched at reference settings. Measuring
// that takes a few seconds for the whole catalog, too slow for plugin load,
// so it is generated at development time:
//
//   cmake --build build --target vf_calibrate
//   ./build/tools/vf_calibrate > core/include/vf/models/AmpCalibration.inc
//
// The core tests fail if the checked-in table no longer matches the models.

#include "vf/dsp/AmpVoice.h"
#include <cstdio>

int main()
{
    const auto t = vf::dsp::AmpVoice::measureCalibration();
    std::printf ("// Generated by tools/vf_calibrate — do not edit. One row per amp model: trims for channels 1-3.\n");
    for (int m = 0; m < vf::models::numAmpModels(); ++m)
        std::printf ("{{ %.4ff, %.4ff, %.4ff }}, // %s\n",
                     static_cast<double> (t[static_cast<size_t> (m * 3)]),
                     static_cast<double> (t[static_cast<size_t> (m * 3 + 1)]),
                     static_cast<double> (t[static_cast<size_t> (m * 3 + 2)]),
                     vf::models::getAmpModel (m).name);
    return 0;
}
